import { dev } from '$app/environment';
import { env } from '$env/dynamic/private';
import { error } from '@sveltejs/kit';

/**
 * Гейт каталога дизайн-системы.
 *
 * /_ds отдаёт внутренний каталог всех шаблонов — на клиентских сайтах его быть не должно.
 *
 * Две разные проверки, и это не дублирование:
 *
 *   prerender — решается на СБОРКЕ. Без флага каталог просто не собирается: иначе
 *     обычный прод-билд полез бы пререндерить 240 страниц и упал бы на 404 из load ниже.
 *
 *   load — решается в РАНТАЙМЕ ($env/dynamic/private). Закрывает случай, когда
 *     собранное с каталогом приложение запущено без флага.
 *
 * Сборка карточек:
 *
 *   DS_CATALOG=1 npm run build
 *
 * Без флага маршрут отвечает 404, как любой несуществующий адрес: отдельного «доступ
 * запрещён» не показываем, чтобы не сообщать о существовании каталога.
 *
 * Здесь именно process.env, а не $env/static/private: статический модуль экспортирует
 * именованные константы и требует, чтобы переменная существовала на сборке — незаданный
 * DS_CATALOG ломал бы каждый обычный билд. Файл серверный и вычисляется в Node на этапе
 * сборки, так что process.env доступен и корректен.
 */
export const prerender = process.env.DS_CATALOG === '1';

export function load() {
	if (!dev && env.DS_CATALOG !== '1') {
		error(404, 'Not Found');
	}

	return {};
}
