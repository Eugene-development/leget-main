/**
 * Контракт единого Hero внутренних страниц шаблона Promo-1.
 *
 * Структура Hero задана раз и навсегда в `./PageHero.svelte`
 * (эталон — Hero страницы «Гарантии») и состоит РОВНО из четырёх элементов
 * сверху вниз: значок → заголовок → линия → текст.
 *
 * Ничего больше в Hero не добавляется: ни надзаголовков, ни кнопок,
 * ни дополнительных линий и абзацев. Страницы отличаются ТОЛЬКО палитрой
 * и иконкой.
 *
 * Страница, которой такой Hero не подходит, берёт собственный блок, а не
 * ослабляет этот, — так 24.08.2026 поступили «Проекты». История уступки и
 * её отката в шапке `PageHero.svelte`.
 */

/** Одно редактируемое поле Hero. */
export type HeroField = {
	/** Ключ в `data` компонента, он же хвост `fieldKey` для EditableField. */
	key: string;
	/** Подпись поля в редакторе. */
	label: string;
	/** Значение с учётом дефолта страницы. */
	value: string;
};

/**
 * Палитра Hero. Только цвета — никакой геометрии, иначе страницы начнут
 * расходиться по структуре.
 */
export type HeroPalette = {
	/** Фон секции (градиент). */
	section: string;
	/** Прозрачность текстуры-ромбов: на тёмном фоне нужна слабее, чем на цветном. */
	patternOpacity: string;
	/** Цвет текстуры-ромбов в URL-encoded виде (#ffffff → %23ffffff). */
	patternColor: string;
	/** Два световых пятна. */
	glowA: string;
	glowB: string;
	/** Плитка значка. */
	iconTile: string;
	/** Линия-разделитель под заголовком и ромб в её центре. */
	rule: string;
	diamond: string;
	/** Текст под линией. */
	text: string;
	/** Цвет заголовка. По умолчанию белый — нужен только светлым палитрам. */
	title?: string;
	/**
	 * Заливка волны. Обязана совпадать с фоном следующей секции страницы,
	 * иначе на стыке будет видна полоса (фон body — #faf9f7, а не #f8fafc).
	 */
	wave: string;
};
