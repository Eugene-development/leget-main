/**
 * Закрытие полосы акций — до конца сессии вкладки.
 *
 * `sessionStorage`, а не `localStorage`: посетитель, закрывший полосу, закрыл её
 * на этот визит, а не навсегда — новая сессия снова показывает акции. Ключ живёт
 * в отдельном модуле, потому что его читают двое: сам компонент (при
 * инициализации, до первого рендера на клиенте) и крошечный скрипт в `app.html`,
 * который до первой отрисовки ставит на `<html>` атрибут-признак.
 *
 * Зачем этот атрибут. Разметка полосы приходит с сервера — сервер о сессии
 * посетителя не знает и знать не может, поэтому SSR всегда отдаёт полосу. Без
 * атрибута закрытая полоса успевала бы отрисоваться и исчезнуть на гидратации:
 * прыжок в самом верху страницы, на каждом переходе. Атрибут выставляется до
 * первой отрисовки, CSS по нему прячет полосу и обнуляет `--promo-h`
 * (см. promo-strip.css) — и до JS-компонента дело доходит уже без мигания.
 *
 * Обе операции защищены try/catch: в приватном режиме и при запрете хранилища
 * обращение к `sessionStorage` бросает, и полоса обязана в этом случае просто
 * работать без памяти, а не падать вместе со страницей.
 */

/** Ключ хранилища. Дублируется литералом в app.html — менять надо в обоих местах. */
export const PROMO_CLOSED_KEY = 'leget:promo-closed';

/** Атрибут-признак на `<html>`. Тоже дублируется в app.html и в promo-strip.css. */
export const PROMO_CLOSED_ATTR = 'data-promo-closed';

/** Закрыта ли полоса в этой сессии. На сервере — всегда `false`. */
export function isPromoClosed(): boolean {
	if (typeof window === 'undefined') return false;

	try {
		return window.sessionStorage.getItem(PROMO_CLOSED_KEY) === '1';
	} catch {
		return false;
	}
}

/** Запомнить закрытие на текущую сессию. */
export function rememberPromoClosed(): void {
	if (typeof window === 'undefined') return;

	document.documentElement.setAttribute(PROMO_CLOSED_ATTR, '');

	try {
		window.sessionStorage.setItem(PROMO_CLOSED_KEY, '1');
	} catch {
		// Хранилище недоступно — полоса всё равно скрыта до перезагрузки.
	}
}
