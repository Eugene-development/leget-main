import { format, resolveConfig } from 'prettier';
import { readFileSync, writeFileSync } from 'node:fs';
import { loadServerModule } from './test-server-module.mjs';
const { contrastDeclarations, resolveColor, SEEDS } = loadServerModule(
	new URL('../src/lib/design-systems/contrast.ts', import.meta.url),
	{}
);
const write = process.argv.includes('--write');
const marker = '\n/* GENERATED CONTRAST PALETTES: npm run contrast:generate */';
let stale = false;
const seedSystems = {};
for (const slug of ['base', 'apple', 'graphite', 'iris', 'ochre']) {
	const file = new URL(`../src/lib/design-systems/${slug}.css`, import.meta.url);
	const original = readFileSync(file, 'utf8');
	const source = original.split(marker)[0].trimEnd();
	const clean = source.replace(/\/\*[\s\S]*?\*\//g, '');
	const blocks = [...clean.matchAll(/([^{}]+)\{([^{}]*)\}/g)].filter((m) => m[1].includes(':root'));
	const tokens = {};
	const sections = [];
	for (const block of blocks) {
		for (const m of block[2].matchAll(/(--ds-[\w-]+):\s*([^;]+);/g)) tokens[m[1]] = m[2].trim();
		if (!tokens['--ds-color-primary']) continue;
		const declarations = contrastDeclarations(tokens);
		sections.push(
			`${block[1].trim()} {\n${declarations.map(([k, v]) => `\t${k}: ${v};`).join('\n')}\n}`
		);
	}
	seedSystems[slug] = Object.fromEntries(
		Object.keys(tokens)
			.filter(
				(k) =>
					/^--ds-cat-\d+-(50|100|300|400|500|600|700)$/.test(k) ||
					/^--ds-accent-panel/.test(k) ||
					/^--ds-alt-petrol-(50|950)$/.test(k) ||
					k === '--ds-university-accent' ||
					k === '--ds-favorite-badge'
			)
			.map((k) => [k, resolveColor(k, tokens)])
	);
	const expected = `${source}\n${marker}\n${sections.join('\n\n')}\n`;
	if (original !== expected) {
		stale = true;
		if (write) writeFileSync(file, expected);
	}
}
const seedFile = new URL('../src/lib/design-systems/contrast-seeds.ts', import.meta.url);
const rawSeedSource = `// Generated by npm run contrast:generate. Category identity stays with the selected system.\nexport const CONTRAST_SEEDS: Record<string, Record<string, string>> = ${JSON.stringify(seedSystems, null, '\t')};\n`;
const seedSource = await format(rawSeedSource, {
	...(await resolveConfig(seedFile.pathname)),
	plugins: [],
	parser: 'typescript'
});
if (write) writeFileSync(seedFile, seedSource);
else if (readFileSync(seedFile, 'utf8') !== seedSource) stale = true;
if (stale && !write) {
	console.error('Stale contrast palettes; run npm run contrast:generate');
	process.exit(1);
}
console.log('Contrast palettes: five systems checked.');
